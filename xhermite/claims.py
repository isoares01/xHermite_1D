"""
Verifiable qualitative claims of the article (Sections 3.1, 4.2, 5.1, 5.3 and 5.4).

``python -m xhermite.claims --outdir <article dir>`` recomputes, symbolically or from
the benchmark CSV files, statements that the text makes without a generated number:

  * the weight w_q is a polynomial of degree 4m for q = 1 - 1/m and the reciprocal
    of a polynomial of degree 4m for q = 1 + 1/m (Lemma 1, consequence);
  * the t^4 coefficient of 1/w_q is -(q-1)/4 (proof of Lemma 6);
  * aliasing of W_4 on the lattice j/16 (Section 5.3): constants c_e, c_o and the
    residues of k^4 modulo 32;
  * fractions quoted in Section 5.1 and Section 5.4 (read from results/assessment_E2.csv):
    share of problems in which the oracle c of M10 lies on a boundary of [-1, 3], and share
    in which the oracle q of M1 is >= 2.5 (unshifted data, level 0).

Writes  results/macros_claims.tex  (macros ``\\clm*``) and  results/claims_report.txt.
"""
from __future__ import annotations

import argparse
import os

import numpy as np
import sympy as sp


def weight_forms():
    """Return {q: (kind, degree)} with kind 'polynomial' or 'rational'."""
    t = sp.symbols("t")
    out = {}
    for q in [sp.Integer(0), sp.Rational(1, 2), sp.Rational(2, 3),
              sp.Rational(3, 2), sp.Integer(2), sp.Rational(4, 3)]:
        x = (q - 1) ** 2 * t ** 4 / 4
        w = sp.simplify((1 - x) ** (1 / (1 - q)))
        num, den = sp.fraction(sp.together(w))
        if sp.Poly(den, t).degree() == 0:
            out[q] = ("polynomial", sp.Poly(num, t).degree())
        else:
            out[q] = ("rational", sp.Poly(den, t).degree())
    return out


def t4_coefficient_of_inverse_weight():
    """Coefficient of t^4 in 1/w_q = (1-x)^{1/(q-1)}; equals -(q-1)/4."""
    q, t = sp.symbols("q t")
    x = (q - 1) ** 2 * t ** 4 / 4
    ser = sp.series((1 - x) ** (1 / (q - 1)), t, 0, 6).removeO()
    return sp.simplify(sp.Poly(ser, t).coeff_monomial(t ** 4))


def aliasing_constants(K: int = 250, a: int = 4, M: int = 16):
    """W_a(j/M)/sin(pi j/M) for even and odd j (a=4, M=16 in the article)."""
    k = np.arange(1, K + 1, dtype=float)
    ratios = {}
    for j in range(1, M):
        s = np.sum(np.sin(np.pi * k ** a * j / M) / (np.pi * k ** a))
        ratios[j] = s / np.sin(np.pi * j / M)
    ce = float(np.mean([v for j, v in ratios.items() if j % 2 == 0]))
    co = float(np.mean([v for j, v in ratios.items() if j % 2 == 1]))
    spread = max(abs(v - (ce if j % 2 == 0 else co)) for j, v in ratios.items())
    residues = sorted({int(kk) ** 4 % 32 for kk in range(1, 60, 2)})
    return ce, co, spread, residues


def benchmark_fractions(outdir: str):
    path = os.path.join(outdir, "results", "assessment_E2.csv")
    if not os.path.exists(path):
        return None
    import pandas as pd
    d = pd.read_csv(path)
    d0 = d[d["level"] == d["level"].min()]
    c = d0["c_card_oracle"]
    lo = float((c <= -1 + 1e-9).mean())
    hi = float((c >= 3 - 1e-9).mean())
    qhigh = float((d0["q_qH0_oracle"] >= 2.5).mean())
    return {"n": int(len(d0)), "c_low": lo, "c_high": hi, "c_boundary": lo + hi, "q_ge_2p5": qhigh}


def build(outdir: str):
    os.makedirs(os.path.join(outdir, "results"), exist_ok=True)
    forms = weight_forms()
    coef = t4_coefficient_of_inverse_weight()
    ce, co, spread, residues = aliasing_constants()
    frac = benchmark_fractions(outdir)
    L = ["Verifiable claims (python -m xhermite.claims)", ""]
    for q, (kind, deg) in forms.items():
        L.append(f"w_q for q={q}: {kind}, degree {deg}")
    L.append(f"t^4 coefficient of 1/w_q: {coef}")
    L.append(f"W_4(j/16)/sin(pi j/16): c_e={ce:.4f} (even j), c_o={co:.4f} (odd j), max spread {spread:.1e}")
    L.append(f"k^4 mod 32 for odd k: {residues}")
    M = ["% generated by `python -m xhermite.claims` -- do not edit by hand",
         f"\\newcommand{{\\clmAliasCe}}{{{ce:.3f}}}%", f"\\newcommand{{\\clmAliasCo}}{{{co:.3f}}}%"]
    if frac:
        L.append(f"benchmark (level 0, {frac['n']} problems): M10 c on boundary {100*frac['c_boundary']:.1f}% "
                 f"(c=-1: {100*frac['c_low']:.1f}%, c=3: {100*frac['c_high']:.1f}%); M1 oracle q>=2.5: {100*frac['q_ge_2p5']:.1f}%")
        M += [f"\\newcommand{{\\clmMtenBoundaryPct}}{{{round(100*frac['c_boundary'])}}}%",
              f"\\newcommand{{\\clmQhighPct}}{{{round(100*frac['q_ge_2p5'])}}}%"]
    else:
        L.append("benchmark fractions skipped: results/assessment_E2.csv not found (run xhermite.assessment first)")
    with open(os.path.join(outdir, "results", "claims_report.txt"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    with open(os.path.join(outdir, "results", "macros_claims.tex"), "w") as fh:
        fh.write("\n".join(M) + "\n")
    print("\n".join(L))
    return dict(forms=forms, coef=coef, ce=ce, co=co, residues=residues, frac=frac)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--outdir", default=".")
    build(ap.parse_args().outdir)


if __name__ == "__main__":
    main()
